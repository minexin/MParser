z = (3 + 4i) * (2 - i);
parts = [real(z), imag(z), abs(z)];
row = [1 + 2i, 3 - 4i];
column = row';
nonconjugated = row.';
single_value = sqrt(single(-1));
hyperbolic = [acosh(-2), asinh(2i), atanh(2)];
rounded_value = round(1.2 + 2.8i);
signed_value = sign(3 + 4i);
finite_checks = [isfinite(1), ~isfinite(inf), isinf(inf), isnan(nan)];
angle = atan2(single(1), 2);
distance = hypot(single(3), 4);
spacing = eps(single(1));

values = single([3 + 4i, 1 + 8i, -3 - 4i]);
reduced_sum = sum(values);
reduced_product = prod(values);
[minimum, minimum_index] = min(values);
running_sum = cumsum(values);
running_product = cumprod(values);
[found_rows, found_columns, found_values] = ...
    find([0, 2 + 3i; 4 - 5i, 0]);

grid = linspace(1 + 2i, 5 - 2i, uint8(3));
single_grid = linspace(single(1), single(2), uint8(3));
typed_zeros = zeros(uint64(2), uint64(3), "single");
typed_ones = ones([1, 3], "uint64");
typed_eye = eye(2, 3, "int16");
typed_infinity = inf(1, 2, "single");
typed_nan = nan(2, 1);
native_ones_sum = sum(typed_ones, "all", "native");
native_eye_sum = sum(typed_eye, "all", "native");
typed_zeros_is_single = isa(typed_zeros, 'single');
typed_ones_is_uint64 = isa(typed_ones, 'uint64');
typed_eye_is_int16 = isa(typed_eye, 'int16');

guarded_total = 0;
for index = 1:24
    guarded_total = guarded_total + sqrt(-1);
end

summary = abs(guarded_total - 24i) + ...
          abs(column(1) - (1 - 2i)) + ...
          abs(nonconjugated(2) - (3 - 4i)) + ...
          abs(single_value - single(1i)) + ...
          abs(hyperbolic(1) - (acosh(2) + pi * 1i)) + ...
          abs(rounded_value - (1 + 3i)) + ...
          abs(signed_value - (0.6 + 0.8i)) + ...
          sum(~finite_checks, "all") + ...
          abs(angle - single(atan(0.5))) + ...
          abs(distance - single(5)) + ...
          abs(spacing - single(1.1920928955078125e-7)) + ...
          abs(reduced_sum - single(1 + 8i)) + ...
          abs(reduced_product - single(199 + 32i)) + ...
          abs(minimum - single(-3 - 4i)) + ...
          abs(minimum_index - 3) + ...
          abs(running_sum(3) - single(1 + 8i)) + ...
          abs(running_product(3) - single(199 + 32i)) + ...
          abs(found_rows(1) - 2) + abs(found_columns(1) - 1) + ...
          abs(found_values(1) - (4 - 5i)) + ...
          abs(grid(2) - 3) + abs(single_grid(2) - single(1.5)) + ...
          sum(abs(typed_zeros), "all") + ...
          double(abs(native_ones_sum - uint64(3))) + ...
          double(abs(native_eye_sum - int16(2))) + ...
          ~typed_zeros_is_single + ...
          ~typed_ones_is_uint64 + ...
          ~typed_eye_is_int16;
summary = summary + sum(~isinf(typed_infinity), "all") + ...
          sum(~isnan(typed_nan), "all");
summary = summary < 1e-12;
