shape_checks = [isscalar(3), isvector(3), ...
                ~isvector([]), isvector(zeros(1, 0)), ...
                isrow(zeros(1, 0)), iscolumn(zeros(0, 1)), ...
                ismatrix(ones(2, 2, 1)), ...
                ~ismatrix(ones(2, 2, 2))];

equality_checks = [isequaln(nan, nan), ...
                   ~isequal(nan, nan), ...
                   isequal(single(1), double(1)), ...
                   isequal(int8(1), uint8(1)), ...
                   ~isequal(int8(-1), uint8(255)), ...
                   isequaln({nan}, {nan}), ...
                   isequaln(struct('x', nan), struct('x', nan))];

mod_values = mod([-7, 7, 7, -7], [3, -3, 3, -3]);
rem_values = rem([-7, 7, 7, -7], [3, -3, 3, -3]);
integer_zero = [mod(int16(5), int16(0)), ...
                rem(int16(5), int16(0))];
next_values = nextpow2([0, 0.5, 1, 7, 8]);
next_integer = nextpow2(int16([-8, 0, 7, 8]));
next_complex = nextpow2([3 + 4i, -3 - 4i]);
signed_absolute = abs([-1 2 -3]);
spaced_subtraction = [1 - 2];
spaced_unary_plus = [1 +2];

guarded_total = 0;
for index = 1:16
    guarded_total = guarded_total + mod(index, 3) + nextpow2(index);
end

summary = sum(~shape_checks, "all") + ...
          sum(~equality_checks, "all") + ...
          sum(abs(mod_values - [2, -2, 1, -1]), "all") + ...
          sum(abs(rem_values - [-1, 1, 1, -1]), "all") + ...
          double(sum(abs(integer_zero - int16([5, 0])), "all")) + ...
          sum(abs(next_values - [0, -1, 0, 3, 3]), "all") + ...
          double(sum(abs(next_integer - int16([3, 0, 3, 3])), "all")) + ...
          sum(abs(next_complex - [3, 3]), "all") + ...
          sum(abs(signed_absolute - [1, 2, 3]), "all") + ...
          abs(spaced_subtraction + 1) + ...
          sum(abs(spaced_unary_plus - [1, 2]), "all") + ...
          abs(guarded_total - 65);
