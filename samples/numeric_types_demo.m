single_value = single(0.1);
int8_values = int8([-inf, -129, -128.5, -1.5, -0.5, 0.5, 1.5, 127.5, inf, nan]);
uint8_values = uint8([-inf, -1, -0.5, 0.5, 1.5, 127.5, inf, nan]);
int16_values = int16([-inf, -40000, 40000, inf]);
uint16_values = uint16([-inf, -1, 70000, inf]);
int32_values = int32([-inf, -3000000000, 3000000000, inf]);
uint32_values = uint32([-inf, -1, 5000000000, inf]);

class_checks = strcmp(class(single_value), 'single') && ...
               strcmp(class(int8_values), 'int8') && ...
               strcmp(class(uint32_values), 'uint32');
isa_checks = isa(single_value, 'single') && ...
             isa(single_value, 'numeric') && ...
             isa(int8_values, 'int8') && ...
             isa(int8_values, 'numeric') && ...
             ~isa(true, 'numeric');
predicate_checks = isnumeric(single_value) && isfloat(single_value) && ...
                   ~isinteger(single_value) && isnumeric(int8_values) && ...
                   isinteger(int8_values) && ~isfloat(int8_values) && ...
                   ~isnumeric(true) && islogical(true);
comparison = int8(5) == 5;

wide = 0x0020000000000001u64;
extended_even = 0x8000000000000002u64;
wide_grid = reshape([wide, wide + uint64(2), ...
                     wide + uint64(4), wide + uint64(6)], 2, 2);
exact_mixed_checks = wide + 1 == uint64(9007199254740994) && ...
                     wide + 0.5 == uint64(9007199254740994) && ...
                     wide * 1.5 == uint64(13510798882111490) && ...
                     wide / 2 == uint64(4503599627370497) && ...
                     mod(wide, 2.5) == uint64(1) && ...
                     mod(wide, Inf) == wide && ...
                     extended_even + 0.5 == extended_even && ...
                     isequal(wide_grid + 0.5, ...
                             wide_grid + uint64(1));

hex_default = 0x2A;
hex_widened = 0x100;
binary_default = 0B101010;
signed_hex = 0xFFs8;
signed_min8 = 0b10000000s8;
signed_min16 = 0x8000s16;
signed_min32 = 0x80000000s32;
signed_min64 = 0x8000000000000000s64;
maximum_hex = 0xFFFFFFFFFFFFFFFFu64;
base_vector = [0b1u16, 0X2U16, 0xFFFFu16];
literal_checks = isa(hex_default, 'uint8') && hex_default == 42 && ...
                 isa(hex_widened, 'uint16') && hex_widened == 256 && ...
                 isa(binary_default, 'uint8') && binary_default == 42 && ...
                 isa(signed_hex, 'int8') && signed_hex == int8(-1) && ...
                 isa(signed_min8, 'int8') && signed_min8 == int8(-128) && ...
                 isa(signed_min16, 'int16') && ...
                 signed_min16 == int16(-32768) && ...
                 isa(signed_min32, 'int32') && ...
                 signed_min32 == int32(-2147483648) && ...
                 isa(signed_min64, 'int64') && ...
                 signed_min64 == int64(-inf) && ...
                 isa(maximum_hex, 'uint64') && ...
                 maximum_hex == uint64(inf) && ...
                 isa(base_vector, 'uint16') && ...
                 isequal(base_vector, uint16([1 2 65535]));

summary = class_checks + isa_checks + predicate_checks + comparison + ...
          literal_checks + exact_mixed_checks;
